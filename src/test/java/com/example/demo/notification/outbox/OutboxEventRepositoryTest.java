package com.example.demo.notification.outbox;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.time.Instant;
import java.util.Collections;
import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;

/**
 * Unit tests for OutboxEventRepository.
 */
@ExtendWith(MockitoExtension.class)
class OutboxEventRepositoryTest {

    @Mock
    private OutboxEventRepository outboxEventRepository;

    private OutboxEvent testEvent;

    @BeforeEach
    void setUp() {
        testEvent = new OutboxEvent("test-event-1", 1L, "TEST_EVENT", "{\"test\": \"data\"}");
        // ID is generated by JPA, don't set manually
        testEvent.setPublicationStatus(OutboxEvent.PublicationStatus.PENDING);
    }

    @Test
    void findPendingEventsReadyForProcessing_ShouldReturnEventsReadyForRetry() {
        // Given
        Instant now = Instant.now();
        List<OutboxEvent> expectedEvents = List.of(testEvent);

        when(outboxEventRepository.findPendingEventsReadyForProcessing(now, 10))
                .thenReturn(expectedEvents);

        // When
        List<OutboxEvent> result = outboxEventRepository.findPendingEventsReadyForProcessing(now, 10);

        // Then
        assertEquals(1, result.size());
        // ID will be generated by JPA in real scenario, so we check other properties
        assertEquals(OutboxEvent.PublicationStatus.PENDING, result.get(0).getPublicationStatus());
        // Either nextRetryAt is null (ready now) or in the past
        assertTrue(result.get(0).getNextRetryAt() == null ||
                   result.get(0).getNextRetryAt().isBefore(now) ||
                   result.get(0).getNextRetryAt().equals(now));

        verify(outboxEventRepository).findPendingEventsReadyForProcessing(now, 10);
    }

    @Test
    void findPendingEventsReadyForProcessing_ShouldReturnEmptyWhenNoEvents() {
        // Given
        Instant now = Instant.now();

        when(outboxEventRepository.findPendingEventsReadyForProcessing(now, 10))
                .thenReturn(Collections.emptyList());

        // When
        List<OutboxEvent> result = outboxEventRepository.findPendingEventsReadyForProcessing(now, 10);

        // Then
        assertTrue(result.isEmpty());

        verify(outboxEventRepository).findPendingEventsReadyForProcessing(now, 10);
    }

    @Test
    void findByEventId_ShouldReturnEventWhenExists() {
        // Given
        String eventId = "test-event-1";

        when(outboxEventRepository.findByEventId(eventId))
                .thenReturn(Optional.of(testEvent));

        // When
        Optional<OutboxEvent> result = outboxEventRepository.findByEventId(eventId);

        // Then
        assertTrue(result.isPresent());
        // ID will be generated by JPA in real scenario
        assertEquals(eventId, result.get().getEventId());
        assertEquals("TEST_EVENT", result.get().getEventType());
        assertEquals(1L, result.get().getAggregateId());

        verify(outboxEventRepository).findByEventId(eventId);
    }

    @Test
    void findByEventId_ShouldReturnEmptyWhenNotExists() {
        // Given
        String eventId = "non-existent-event";

        when(outboxEventRepository.findByEventId(eventId))
                .thenReturn(Optional.empty());

        // When
        Optional<OutboxEvent> result = outboxEventRepository.findByEventId(eventId);

        // Then
        assertFalse(result.isPresent());

        verify(outboxEventRepository).findByEventId(eventId);
    }

    @Test
    void countByPublicationStatus_ShouldReturnCorrectCount() {
        // Given
        OutboxEvent.PublicationStatus status = OutboxEvent.PublicationStatus.PENDING;
        long expectedCount = 5L;

        when(outboxEventRepository.countByPublicationStatus(status))
                .thenReturn(expectedCount);

        // When
        long result = outboxEventRepository.countByPublicationStatus(status);

        // Then
        assertEquals(expectedCount, result);

        verify(outboxEventRepository).countByPublicationStatus(status);
    }

    @Test
    void findByPublicationStatusOrderByCreatedAtDesc_ShouldReturnEventsInCorrectOrder() {
        // Given
        OutboxEvent.PublicationStatus status = OutboxEvent.PublicationStatus.FAILED;
        OutboxEvent olderEvent = new OutboxEvent("older-event", 1L, "TEST_EVENT", "{}");
        olderEvent.setPublicationStatus(status);
        olderEvent.setCreatedAt(Instant.now().minusSeconds(10));
        OutboxEvent newerEvent = new OutboxEvent("newer-event", 1L, "TEST_EVENT", "{}");
        newerEvent.setPublicationStatus(status);
        newerEvent.setCreatedAt(Instant.now());
        List<OutboxEvent> expectedEvents = List.of(newerEvent, olderEvent); // Descending order

        when(outboxEventRepository.findByPublicationStatusOrderByCreatedAtDesc(status))
                .thenReturn(expectedEvents);

        // When
        List<OutboxEvent> result = outboxEventRepository.findByPublicationStatusOrderByCreatedAtDesc(status);

        // Then
        assertEquals(2, result.size());
        assertEquals(newerEvent.getEventId(), result.get(0).getEventId()); // Newer first
        assertEquals(olderEvent.getEventId(), result.get(1).getEventId()); // Older second

        verify(outboxEventRepository).findByPublicationStatusOrderByCreatedAtDesc(status);
    }

    @Test
    void findByPublicationStatusAndNextRetryAtGreaterThanEqual_ShouldReturnEventsWaitingForRetry() {
        // Given
        OutboxEvent.PublicationStatus status = OutboxEvent.PublicationStatus.PENDING;
        Instant now = Instant.now();
        Instant futureTime = now.plusSeconds(30); // Event ready in 30 seconds
        OutboxEvent futureEvent = new OutboxEvent("future-event", 1L, "TEST_EVENT", "{}");
        futureEvent.setPublicationStatus(status);
        futureEvent.setNextRetryAt(futureTime);
        List<OutboxEvent> expectedEvents = List.of(futureEvent);

        when(outboxEventRepository.findByPublicationStatusAndNextRetryAtGreaterThanEqualOrderByNextRetryAtAsc(
                eq(status), eq(now)))
                .thenReturn(expectedEvents);

        // When
        List<OutboxEvent> result = outboxEventRepository.findByPublicationStatusAndNextRetryAtGreaterThanEqualOrderByNextRetryAtAsc(
                status, now);

        // Then
        assertEquals(1, result.size());
        assertEquals(futureEvent.getEventId(), result.get(0).getId());
        assertEquals(status, result.get(0).getPublicationStatus());
        assertTrue(result.get(0).getNextRetryAt().isAfter(now) ||
                   result.get(0).getNextRetryAt().equals(now));

        verify(outboxEventRepository).findByPublicationStatusAndNextRetryAtGreaterThanEqualOrderByNextRetryAtAsc(
                eq(status), eq(now));
    }
}